"""Generate docs/EVAL_REPORT.md (and the README results table) from results/*.json.

Every number in the report is read from results/; nothing is typed in by hand.

    python -m chaos.report
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from chaos.harness import CONFIGS, RESULTS, ROOT

REPORT = ROOT / "docs" / "EVAL_REPORT.md"
README = ROOT / "README.md"
POINTS = ["before_intent_fsync", "after_intent_before_effect", "after_effect_before_result", "llm_mid", "random"]


def load(name: str) -> dict | None:
    p = RESULTS / f"chaos_{name}_summary.json"
    return json.loads(p.read_text()) if p.exists() else None


def ms(x: float | None) -> str:
    return "n/a" if x is None else f"{x:.2f}"


def table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def bench() -> dict | None:
    p = RESULTS / "bench.json"
    return json.loads(p.read_text()) if p.exists() else None


def step_overheads(b: dict | None) -> str:
    if not b:
        return "not measured"
    s = {r["policy"]: r for r in b["steps"]}
    parts = [f"{p} +{s[p]['overhead_us_p50']:.0f} µs" for p in ("always", "group:8:5", "none") if p in s]
    return ", ".join(parts)


def headline(b: dict | None) -> tuple[str, str]:
    rows = []
    label = {"b0": "B0 naive restart", "b1": "B1 checkpoint-after-step", "aw": "AgentWAL"}
    dates, n = set(), []
    for name in ("b0", "b1", "aw"):
        s = load(name)
        if not s:
            continue
        dates.add(s["date"])
        n.append(s["runs"])
        rows.append([
            label[name], s["runs"], s["total_kills"], s["duplicated_effects"], s["lost_effects"],
            s["runs_with_violation"], f"{ms(s['recovery_ms_p50'])} / {ms(s['recovery_ms_p99'])}",
            s["llm_calls_wasted_total"],
            step_overheads(b) if name == "aw" else "0 (no journal)",
        ])
    t = table(["Strategy", "Runs", "Kills", "Duplicated effects", "Lost effects", "Runs violating an invariant",
               "Recovery p50 / p99 (ms)", "LLM calls re-billed", "Per-step overhead vs no journal (p50)"], rows)
    note = (f"Fake model, `kill -9` process crashes, {', '.join(map(str, n))} runs, measured {', '.join(sorted(dates))}. "
            "Generated by `make chaos` + `make bench`; see docs/EVAL_REPORT.md.")
    return t, note


def build() -> str:
    b = bench()
    head, note = headline(b)
    L = ["# AgentWAL evaluation report", "",
         "_Generated by `python -m chaos.report` from `results/`. Do not edit by hand; rerun `make chaos bench report`._", ""]
    all_s = {n: load(n) for n in CONFIGS}
    present = {n: s for n, s in all_s.items() if s}
    total_kills = sum(s["total_kills"] for n, s in present.items() if n != "smoke")
    total_runs = sum(s["runs"] for n, s in present.items() if n != "smoke")
    L += ["## Summary", "",
          f"Across all suites: **{total_runs:,} runs and {total_kills:,} SIGKILLs** "
          "(each run killed at least once, restarted until complete, at most 10 restarts).", "",
          head, "", note, "",
          "Invariants checked per run: (1) exactly one payment per intended refund, none missing, correct amount; "
          "(2) final output identical to an uninterrupted reference run; (3) every record acknowledged before a "
          "kill survives recovery; (4) no `NonDeterminismError`. A run that never completes counts as a violation.", ""]

    # where the kills went
    rows = []
    for n, s in present.items():
        kp = s["kills_by_point"]
        rows.append([n, s["runs"], s["total_kills"], *[kp.get(p, 0) for p in POINTS], s["restarts_total"], s["timer_misses"]])
    L += ["## Kills per suite and kill point", "",
          "`random` = SIGKILL from a harness timer at a uniformly random moment of the run (including start-up). "
          "The others are targeted kill points the agent reaches (see `agentwal.KILL_POINTS`). "
          "`timer misses` = first attempts that finished before the timer fired; those runs were redone under a new run id "
          "so that every reported run took at least one kill.", "",
          table(["Suite", "Runs", "Kills", *POINTS, "Restarts", "Timer misses"], rows), ""]

    aw = present.get("aw")
    if aw and aw["random_kills_landed_after"]:
        L += ["Where the random kills on the `aw` suite landed (type of the last record in the journal at the kill; "
              "`EMPTY` = killed before the journal was created):", "",
              table(["Last record", "Random kills"], [[k, v] for k, v in aw["random_kills_landed_after"].items()]), "",
              "Many random kills land during interpreter start-up (`EMPTY`) or while the fake model is \"thinking\" "
              "(`LLM_CALL`), because that is where the time goes; the effect windows are only microseconds wide, which is "
              "why the targeted kill points exist.", ""]

    # all suites, full invariants
    rows = []
    for n, s in present.items():
        rows.append([n, s["description"], s["runs"], s["duplicated_effects"], s["lost_effects"], s["wrong_effects"],
                     s["acked_record_lost"], s["nondeterminism_errors"], s["runs_with_violation"],
                     ", ".join(f"{k}: {v}" for k, v in s["violations_by_type"].items()) or "-"])
    L += ["## All suites", "",
          table(["Suite", "What it tests", "Runs", "Dup", "Lost", "Wrong", "Acked lost", "NDE", "Violating runs",
                 "Violations by type"], rows), ""]

    # power loss
    rows = []
    for n in ("aw-pl-always", "aw-pl-group", "aw-pl-none", "aw-pl-always-stoch", "aw-pl-none-stoch"):
        s = present.get(n)
        if s:
            rows.append([n, s["settings"]["fsync"], "sampled" if s["settings"]["stochastic"] else "deterministic",
                         s["runs"], s["total_kills"], s["runs_with_violation"], s["acked_record_lost"],
                         s["llm_calls_wasted_total"], f"{s['llm_calls_billed_mean']:.2f}" if s["llm_calls_billed_mean"] else "n/a"])
    if rows:
        L += ["## Process crash vs power loss, per fsync policy", "",
              "`kill -9` alone cannot test fsync: the page cache survives a process crash. These suites use "
              "`PowerLossJournal`, which keeps un-fsynced records in user space, so a SIGKILL loses exactly what a "
              "power failure would lose. `LLM calls re-billed` counts completed runs only (10 calls are needed).", "",
              table(["Suite", "fsync", "Model", "Runs", "Kills", "Violating runs", "Acked records lost",
                     "LLM calls re-billed", "Billed calls / completed run"], rows), ""]
        ns = present.get("aw-pl-none-stoch")
        if ns:
            errs: dict[str, int] = {}
            for line in (RESULTS / "chaos_aw-pl-none-stoch.jsonl").read_text().splitlines():
                for e in json.loads(line)["errors"]:
                    k = "409 idempotency key reused with different parameters" if "409" in e else e[:80]
                    errs[k] = errs.get(k, 0) + 1
            L += ["How to read this: with a deterministic model even `none` stays correct, because the idempotency key is "
                  "derived from `(run_id, seq)` and the receiver deduplicates; what `none` costs is re-billed LLM calls "
                  "(the whole journal is lost at each crash). With a sampled model, `none` breaks resume: a lost "
                  "`LLM_RESULT` is re-sampled, a different amount is sent under the old key, and the receiver rejects it. "
                  f"Errors in `aw-pl-none-stoch`: {', '.join(f'{v}× {k}' for k, v in errs.items()) or 'none'}. "
                  f"No money moved incorrectly ({ns['duplicated_effects']} duplicated, {ns['wrong_effects']} wrong), but "
                  "those runs cannot finish without a human. With `always` or group commit, the barrier before each effect "
                  "makes the decision durable before it is acted on, so the same sampled model has no violations.", ""]

    rows = []
    for n in ("aw", "aw-noidem", "aw-reconcile-noidem"):
        s = present.get(n)
        if s:
            st = s["settings"]
            rows.append([n, "yes" if st["idempotent_service"] else "no", st["recovery"], s["runs"],
                         s["kills_by_point"].get("after_effect_before_result", 0), s["duplicated_effects"],
                         s["runs_with_violation"]])
    if rows:
        L += ["## The receiver assumption", "",
              "An intent without a result is ambiguous: the effect may or may not have happened. AgentWAL either "
              "retries with the same idempotency key (safe only if the receiver deduplicates) or asks the receiver "
              "`GET /payments?key=` first (reconcile).", "",
              table(["Suite", "Receiver deduplicates", "Recovery", "Runs", "Kills after effect, before result",
                     "Duplicated effects", "Violating runs"], rows), ""]

    s = present.get("aw-torn")
    if s:
        L += ["## Torn writes", "",
              f"After every kill the journal was truncated at a uniformly random byte offset ({s['total_kills']} tears "
              f"over {s['runs']} runs); recovery truncates to the last valid record and replay re-executes the rest "
              f"with the same idempotency keys. Violating runs: **{s['runs_with_violation']}**, duplicated effects: "
              f"{s['duplicated_effects']}, lost effects: {s['lost_effects']}.", "",
              "Unit and property tests cover the same at the record level (`tests/property/test_props.py`: "
              "truncation at any offset recovers exactly a prefix; a single corrupted byte never yields a wrong record).", ""]

    rows = [[n, ms(s["recovery_ms_p50"]), ms(s["recovery_ms_p99"]), s["recoveries_measured"],
             f"{s['journal_bytes_mean']:.0f}"] for n, s in present.items()]
    L += ["## Recovery time and journal size", "",
          "Recovery time = journal open + CRC scan + torn-tail truncation + replay up to the first live call, "
          "measured inside the restarted process (interpreter start-up excluded). B1 = reading the checkpoint; "
          "B0 has nothing to recover.", "",
          table(["Suite", "Recovery p50 (ms)", "p99 (ms)", "Restarts measured", "Final journal bytes (mean)"], rows), ""]

    if b:
        L += ["## Overhead benchmark", "", f"`make bench` on {b['machine']}, {b['date']}. {b['note']}", "",
              "Raw append latency (2,000 records of ~260 bytes):", "",
              table(["Policy", "p50 (µs)", "p99 (µs)", "mean (µs)", "fsyncs"],
                    [[r["policy"], f"{r['p50_us']:.1f}", f"{r['p99_us']:.1f}", f"{r['mean_us']:.1f}", r["fsyncs"]]
                     for r in b["append"]]), "",
              "Per agent step (one ticket: an LLM call and, for 7 of 10 tickets, a refund), zero-latency fake model "
              "and in-memory payments, so the journal cost is not hidden behind network time:", "",
              table(["Policy", "step p50 (µs)", "step p99 (µs)", "overhead p50 (µs)", "journal bytes / step"],
                    [[r["policy"], f"{r['step_us_p50']:.0f}", f"{r['step_us_p99']:.0f}", f"{r['overhead_us_p50']:.0f}",
                      f"{r['journal_bytes_per_step']:.0f}"] for r in b["steps"]]), "",
              "Even `+full` is small next to a real LLM call (hundreds of ms to seconds).", ""]

    real = present.get("real")
    L += ["## Real-model runs", ""]
    if real:
        L += [f"{real['runs']} runs with `{real['settings']['model']}` ({real['date']}): {real['total_kills']} kills, "
              f"{real['runs_with_violation']} violating runs, {real['duplicated_effects']} duplicated effects, "
              f"total cost ${real['llm_cost_usd_total']:.4f}, LLM calls re-billed: {real['llm_calls_wasted_total']}. "
              "Invariant 2 is checked as consistency (payments = the decisions in the output) because a sampled "
              "model has no single reference output.", ""]
    else:
        L += ["Not run yet. `make chaos-real` runs a one-run pilot, prints its cost and asks before the 30 runs.", ""]
    L += ["## Reproduce", "", "```bash", "make setup", "make test", "make chaos      # fake model, no API key", "make bench",
          "make report", "```", ""]
    return "\n".join(L)


def update_readme() -> None:
    if not README.exists():
        return
    b = bench()
    head, note = headline(b)
    text = README.read_text()
    new = f"<!-- RESULTS:START -->\n{head}\n\n{note}\n<!-- RESULTS:END -->"
    text2 = re.sub(r"<!-- RESULTS:START -->.*?<!-- RESULTS:END -->", lambda _m: new, text, flags=re.S)
    README.write_text(text2)


def main() -> None:
    REPORT.write_text(build())
    update_readme()
    print(f"wrote {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
